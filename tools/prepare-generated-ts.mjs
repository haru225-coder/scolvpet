#!/usr/bin/env node
// TS 客户端生成后处理(对齐 tools/prepare-generated-dart.mjs 的角色):
// openapi-generator 7.x 对 nullable oneOf 会 import "./Null" 但不生成该模型,
// 这里补一个语义正确的桩。幂等:内容固定,重复生成结果一致(drift 检查友好)。
import fs from 'node:fs';
import path from 'node:path';

const root = process.env.GENERATED_TS_ROOT
  ? path.resolve(process.env.GENERATED_TS_ROOT)
  : path.resolve('generated/ts/scolvpet-api');
const srcDir = path.join(root, 'src');
const modelsDir = path.join(srcDir, 'models');

const referencesNull = fs
  .readdirSync(modelsDir)
  .filter((f) => f.endsWith('.ts'))
  .some((f) => /from ['"]\.\/Null['"]/.test(fs.readFileSync(path.join(modelsDir, f), 'utf8')));

const nullStub = `/* Generated by tools/prepare-generated-ts.mjs — openapi-generator emits
 * imports of "./Null" for nullable oneOf branches without generating it. */
export type Null = null;

export function NullFromJSON(_json: unknown): Null {
  return null;
}

export function NullFromJSONTyped(_json: unknown, _ignoreDiscriminator: boolean): Null {
  return null;
}

export function NullToJSON(_value?: Null | null): unknown {
  return null;
}

export function NullToJSONTyped(_value?: Null | null, _ignoreDiscriminator?: boolean): unknown {
  return null;
}

export function instanceOfNull(value: unknown): value is Null {
  return value === null;
}
`;

const target = path.join(modelsDir, 'Null.ts');
if (referencesNull) {
  fs.writeFileSync(target, nullStub);
  console.log('prepare-generated-ts: wrote models/Null.ts stub');
} else if (fs.existsSync(target)) {
  fs.rmSync(target);
  console.log('prepare-generated-ts: removed stale models/Null.ts');
} else {
  console.log('prepare-generated-ts: no Null stub needed');
}

